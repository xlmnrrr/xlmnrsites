def project(lat, lon):
    """(lat, lon) → (x, y) in planet diameters, origin at the top of the horizon circle."""
    la = math.radians(lat)
    dl = math.radians(lon - LON0)
    x = K * math.cos(la) * math.sin(dl)
    d = min(1.0, max(0.0, (LAT_TOP - lat) / (LAT_TOP - LAT_BOT)))
    limb = 0.5 - math.sqrt(max(0.0, 0.25 - x * x))
    y = limb + 0.004 + DEPTH * d ** 1.35
    return x, y, d


def to_px(x, y):
    return (x / X_SPAN + 0.5) * W, y / Y_SPAN * H


buf = np.zeros((H, W), np.float32)    # light energy
core = np.zeros((H, W), np.float32)   # bright city centres (whiter tint)


def stamp(target, px, py, sx, sy, amp):
    r = 3.2
    x0, x1 = int(max(0, px - r * sx)), int(min(W, px + r * sx + 1))
    y0, y1 = int(max(0, py - r * sy)), int(min(H, py + r * sy + 1))
    if x0 >= x1 or y0 >= y1:
        return
    xs = (np.arange(x0, x1) - px) / sx
    ys = (np.arange(y0, y1) - py) / sy
    target[y0:y1, x0:x1] += amp * np.exp(-0.5 * (ys[:, None] ** 2 + xs[None, :] ** 2))


def squash(d):
    # the closer to the limb, the flatter everything looks
    return 0.32 + 0.68 * d


def light(lat, lon, size, amp, target=None):
    x, y, d = project(lat, lon)
    px, py = to_px(x, y)
    hs = max(0.35, math.cos(math.radians(lon - LON0)))
    stamp(target if target is not None else buf, px, py, size * hs, size * squash(d), amp)


